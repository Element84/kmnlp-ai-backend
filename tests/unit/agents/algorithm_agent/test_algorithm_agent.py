from collections.abc import Callable
from typing import Any
from unittest.mock import patch

import pytest
from e84_geoai_common.llm.models.claude import BedrockClaudeLLM
from e84_geoai_common.llm.tests.mock_bedrock_runtime import (
    _MockBedrockRuntimeClient,  # type: ignore[reportPrivateUsage]
    claude_response_with_content,
    make_test_bedrock_runtime_client,
)
from rich import print as rich_print
from shapely.geometry import box

from llm_agent import ALGORITHM_AGENT_DEFAULT_LLM_MODEL_ID
from llm_agent.agents.algorithm_agent.algorithm.base import make_function_call_model
from llm_agent.agents.algorithm_agent.algorithm.exec import execute_algorithm
from llm_agent.agents.algorithm_agent.algorithm_agent import AlgorithmAgent
from llm_agent.agents.algorithm_agent.interface import (
    AlgorithmProblemSpec,
    AlgorithmSolutionSpec,
    input_vars_to_function_set,
)
from llm_agent.context import LLMAgentContext, ToolCallContext
from tests.unit.agents.algorithm_agent.utils import make_test_data_array_spatiotemporal, test_params


@pytest.mark.parametrize(
    ("problem", "dummy_solution"),
    [(params["problem"], params["dummy_solution"]) for params in test_params.values()],
    ids=test_params.keys(),
)
@pytest.mark.asyncio
async def test_solution(
    global_context: Callable[..., LLMAgentContext],
    problem: AlgorithmProblemSpec,
    dummy_solution: dict[str, Any],
) -> None:
    """Test whether the solution runs without errors.

    If USE_REAL_BEDROCK_CLIENT=true is set, the mock solution will be ignored
    in favor of the solution generated by a real Bedrock call.
    """
    dummy_response = claude_response_with_content(
        [
            {
                "id": "tool_use_01",
                "name": "AlgorithmSolutionTool",
                "input": dummy_solution,
            },
            {
                "id": "tool_use_02",
                "name": "EndTurnTool",
                "input": {},
            },
        ],
        overrides={"stop_reason": "tool_use"},
    )
    client = make_test_bedrock_runtime_client([dummy_response])
    llm = BedrockClaudeLLM(model_id=ALGORITHM_AGENT_DEFAULT_LLM_MODEL_ID, client=client)

    function_set = input_vars_to_function_set(problem.inputs_provided)
    function_call_model = make_function_call_model(function_set.functions)

    agent = AlgorithmAgent(llm, problem=problem, function_call_type=function_call_model)
    async for output in agent.run_typed(global_context(), inp=problem):
        if isinstance(output, AlgorithmSolutionSpec):
            solution = output
            break
    else:
        pytest.fail("Did not receive AlgorithmSolutionSpec from agent")

    # print out solution if doing a live test
    if not isinstance(client, _MockBedrockRuntimeClient):
        rich_print(f"Problem: {problem}")
        print("---AlgorithmSolutionSpec---\n")  # noqa: T201
        print(f"Thoughts:\n{solution.thoughts}\n")  # noqa: T201
        rich_print(f"Algorithm:\n{solution.algorithm}\n")
        print(f"Explanation:\n{solution.explanation}\n")  # noqa: T201
        print("---------------------------")  # noqa: T201

    sst = make_test_data_array_spatiotemporal(start_date="2024-01-01", num_time_steps=365)

    tool_call_context = ToolCallContext(tool_call_id="", global_context=global_context())

    # mock calls to geocode_natural_language_description() so that they always
    # return a fixed geometry without making any Bedrock calls.
    with patch(
        # the path is to the module where it's used, not where it's defined
        "llm_agent.agents.algorithm_agent.algorithm.exec.geocode_natural_language_description",
        return_value=box(-10, -10, 10, 10),
    ):
        await execute_algorithm(tool_call_context, solution.algorithm, input_vars={"sst": sst})
