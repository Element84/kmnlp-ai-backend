import os
from unittest.mock import patch

import pytest
from e84_geoai_common.llm.core import LLMInferenceConfig
from e84_geoai_common.llm.models.claude import (
    CLAUDE_BEDROCK_MODEL_IDS,
    BedrockClaudeLLM,
)
from e84_geoai_common.llm.tests.mock_bedrock import (
    _MockBedrockRuntimeClient,
    claude_response_with_content,
    make_test_bedrock_client,
)
from rich import print as rich_print
from shapely.geometry import box

from llm_agent.agents.algorithm_agent.algorithm import (
    DataArrayFunctionSet,
    GeneralPlottingFunctionSet,
    execute_algorithm,
)
from llm_agent.agents.algorithm_agent.algorithm_agent import (
    DEFAULT_MAX_OUTPUT_TOKENS,
    AlgorithmAgent,
)
from llm_agent.agents.algorithm_agent.interface import (
    AlgorithmProblemSpec,
    AlgorithmSolutionSpec,
)
from tests.agents.algorithm_agent.utils import (
    make_dummy_data_array,
    test_params,
)


@pytest.mark.parametrize(
    ("problem", "dummy_solution"),
    [
        (params["problem"], params["dummy_solution"])
        for params in test_params.values()
    ],
    ids=test_params.keys(),
)
def test_solution(
    problem: AlgorithmProblemSpec, dummy_solution: AlgorithmSolutionSpec
) -> None:
    """Test whether the solution runs without errors.

    If USE_REAL_BEDROCK_CLIENT=true is set, the mock solution will be ignored
    in favor of the solution generated by a real Bedrock call.
    """
    if dummy_solution[0] == "{":
        # because we're using json_mode=True and because of how that works with
        # Claude, the LLM's response is supposed to start after '{'.
        dummy_solution = dummy_solution[1:]
    dummy_response = claude_response_with_content(dummy_solution)
    client = make_test_bedrock_client([dummy_response])
    llm = BedrockClaudeLLM(
        model_id=CLAUDE_BEDROCK_MODEL_IDS["Claude 3.5 Sonnet"], client=client
    )
    agent = AlgorithmAgent(
        llm,
        problem_spec=AlgorithmProblemSpec,
        solution_spec=AlgorithmSolutionSpec[
            DataArrayFunctionSet | GeneralPlottingFunctionSet
        ],
        inference_cfg=LLMInferenceConfig(
            temperature=float(os.getenv("TEMPERATURE", "0")),
            max_tokens=DEFAULT_MAX_OUTPUT_TOKENS,
        ),
    )
    solution = agent.run(problem)

    # print out solution if doing a live test
    if not isinstance(client, _MockBedrockRuntimeClient):
        rich_print(f"Problem: {problem}")
        print("---AlgorithmSolutionSpec---\n")  # noqa: T201
        print(f"Thoughts:\n{solution.thoughts}\n")  # noqa: T201
        rich_print(f"Algorithm:\n{solution.algorithm}\n")
        print(f"Explanation:\n{solution.explanation}\n")  # noqa: T201
        print("---------------------------")  # noqa: T201

    sst = make_dummy_data_array(start_date="2024-01-01", num_time_steps=365)

    # mock calls to geocode_natural_language_description() so that they always
    # return a fixed geometry without making any Bedrock calls.
    with patch(
        # the path is to the module where it's used, not where it's defined
        "llm_agent.agents.algorithm_agent.algorithm.exec.geocode_natural_language_description",
        return_value=box(-10, -10, 10, 10),
    ):
        execute_algorithm(solution.algorithm, input_vars={"sst": sst})
